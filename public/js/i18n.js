// i18n.js — 轻量前端国际化（无第三方依赖）：t(key, params) + setLang/getLang + 语言选择器挂件。
// 语言：zh / en / fr / ru / es / pt。缺失键回退到 zh，其次回退到 key。
'use strict';

export const LANGS = [
  { code: 'zh', label: '简体中文', en: 'Chinese' },
  { code: 'en', label: 'English', en: 'English' },
  { code: 'fr', label: 'Français', en: 'French' },
  { code: 'ru', label: 'Русский', en: 'Russian' },
  { code: 'es', label: 'Español', en: 'Spanish' },
  { code: 'pt', label: 'Português', en: 'Portuguese' },
];

const KEY = 'nf_lang';
let current = 'zh';

try { current = localStorage.getItem(KEY) || 'zh'; } catch (e) { /* ignore */ }
if (!LANGS.some((l) => l.code === current)) current = 'zh';

export function getLang() { return current; }

export function setLang(code) {
  if (!LANGS.some((l) => l.code === code)) return false;
  current = code;
  try { localStorage.setItem(KEY, code); } catch (e) { /* ignore */ }
  document.documentElement.lang = code;
  return true;
}

/**
 * 翻译：key 支持 a.b.c 点路径；params 用 {name} 占位符替换。
 * 先查当前语言，再回退 zh，最后返回 key。
 */
export function t(key, params) {
  const dict = DICTS[current] || {};
  let s = dict[key] != null ? dict[key] : ((DICTS.zh && DICTS.zh[key]) != null ? DICTS.zh[key] : key);
  if (params) {
    for (const [k, v] of Object.entries(params)) s = String(s).replace(new RegExp('\\{' + k + '\\}', 'g'), String(v));
  }
  return s;
}

/** Html 安全版：转义后翻译（用于 innerHTML 场景）。 */
export function tHtml(key, params) {
  return t(key, params).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

/** 在给定容器中追加一个语言选择器（select），change 时 setLang 并刷新页面。 */
export function langSelect(onChange) {
  const sel = document.createElement('select');
  sel.className = 'lang-select';
  for (const l of LANGS) {
    const o = document.createElement('option');
    o.value = l.code;
    o.textContent = l.en;
    if (l.code === current) o.selected = true;
    sel.appendChild(o);
  }
  sel.addEventListener('change', () => {
    if (setLang(sel.value)) {
      if (typeof onChange === 'function') onChange(sel.value);
      else location.reload();
    }
  });
  return sel;
}

